// Get all cities for a given region
export function getCitiesForRegion(regionId: string): CityInfo[] {
  return REGION_CITIES[regionId] || [];
}

// Get a specific city's coordinates
export function getCityCoords(regionId: string, cityName: string): { lat: number; lon: number } | null {
  const cities = REGION_CITIES[regionId];
  if (!cities) return null;
  const city = cities.find((c) => c.name === cityName);
  return city ? { lat: city.lat, lon: city.lon } : null;
}
